function appendReplyHardRulesLocal(systemPrompt, row = {}) {
  const product = String(row?.product || '').trim();
  return [sanitizeLearnedStylePrompt(systemPrompt), '', buildReplyHardRulesSuffixLocal(product)].join('\n');
}

